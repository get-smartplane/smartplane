/**
 * Regenerates the integrations catalog from the curated Activepieces packages:
 *   src/generated/catalog.json         every piece, action, input schema, support status and shard (decoded by apps)
 *   src/generated/pieces/<shard>.ts    static loaders per runner Worker, so wrangler bundles exactly that shard's pieces
 * Run with `bun run generate` in packages/integrations.
 */
import { IntegrationCatalog, type IntegrationPiece } from "@pc/domain"
import { Schema } from "effect"
import { createRequire } from "node:module"
import { curatedPieces } from "../src/curation"
import { describePiece } from "../src/describe"
import { findPiece } from "../src/piece-shape"
import { shards } from "../src/shards"
import { compileInputSchema } from "../src/validation"

const require = createRequire(import.meta.url)
const PackageJson = Schema.Struct({ version: Schema.String })
const generated = new URL("../src/generated/", import.meta.url)

/** An action whose input schema the runtime cannot compile must not be offered. */
const checkSchemas = (piece: IntegrationPiece): IntegrationPiece => {
  const actions = piece.actions.map((action) => {
    if (action.support.status !== "supported") return action
    try {
      compileInputSchema(action.inputSchema)
      return action
    } catch (error) {
      return { ...action, support: { status: "unsupported" as const, reason: `Input schema not supported: ${String(error)}` } }
    }
  })
  return { ...piece, actions, supportedActionCount: actions.filter((action) => action.support.status === "supported").length }
}

const load = (packageName: string): unknown => {
  try {
    return require(packageName)
  } catch (error) {
    throw new Error(`${packageName} failed to load: ${error instanceof Error ? error.message : String(error)}`)
  }
}

const pieces = curatedPieces.map((curated) => {
  const piece = findPiece(load(curated.packageName))
  if (piece === undefined) throw new Error(`${curated.packageName} does not export a piece`)
  const { version } = Schema.decodeUnknownSync(PackageJson)(require(`${curated.packageName}/package.json`))
  return checkSchemas(describePiece(curated, version, piece))
})

const catalog = Schema.encodeSync(Schema.toCodecJson(IntegrationCatalog))({ source: { framework: "activepieces", license: "MIT" }, pieces })
await Bun.write(new URL("catalog.json", generated), `${JSON.stringify(catalog)}\n`)

const registry = (shard: string) => {
  const loaders = curatedPieces.filter((curated) => curated.shard === shard)
    .map(({ id, packageName }) => `  ${JSON.stringify(id)}: () => import(${JSON.stringify(packageName)})`)
  return `// Generated by scripts/generate.ts from src/curation.ts. Do not edit.
/// <reference path="../../activepieces.d.ts" />
import type { PieceLoaders } from "../../shards"

/** The ${shard} shard's pieces. Lazy: a piece is evaluated on its first run, not when the Worker starts. */
export const pieceLoaders: PieceLoaders = {
${loaders.join(",\n")}
}
`
}
for (const shard of shards) await Bun.write(new URL(`pieces/${shard}.ts`, generated), registry(shard))

const width = Math.max(...pieces.map((piece) => piece.id.length))
for (const piece of pieces) {
  const unsupported = piece.actions.filter((action) => action.support.status === "unsupported").length
  const superseded = piece.actions.filter((action) => action.support.status === "superseded").length
  console.log(
    `${piece.id.padEnd(width)} ${piece.shard.padEnd(8)} v${piece.version.padEnd(8)} auth=${piece.authTypes.join("|").padEnd(28)} actions=${piece.actionCount} supported=${piece.supportedActionCount} superseded=${superseded} unsupported=${unsupported}`
  )
}
